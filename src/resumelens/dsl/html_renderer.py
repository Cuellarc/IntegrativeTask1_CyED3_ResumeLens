def _paragraph(label: str, value: str) -> str:
    return f"<p><strong>{label}:</strong> {escape(value)}</p>"


# Renders a validated candidate profile model as HTML.
def render_html(model: object) -> str:
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '    <meta charset="UTF-8">',
        '    <meta name="viewport" content="width=device-width, initial-scale=1.0">',
        "    <title>ResumeLens - Candidate Profile</title>",
        f"    <style>{_STYLE}</style>",
        "</head>",
        "<body>",
        '<div class="candidate-card">',
        '<div class="header">',
        f"    <h1>{escape(model.name)}</h1>",
        "    <p>Candidate Profile generated by ResumeLens</p>",
        "</div>",
    ]

    personal_information = []

    if getattr(model, "email", None):
        personal_information.append(_paragraph("Email", model.email))

    if getattr(model, "phone", None):
        personal_information.append(_paragraph("Phone", model.phone))

    for link in getattr(model, "links", []):
        personal_information.append(_paragraph("Link", link))

    if getattr(model, "location", None):
        personal_information.append(_paragraph("Location", model.location))

    if getattr(model, "current_role", None):
        personal_information.append(
            _paragraph("Current role", model.current_role)
        )

    if personal_information:
        parts.extend([
            '<div class="section">',
            "    <h2>Personal Information</h2>",
            *personal_information,
            "</div>",
        ])

    if getattr(model, "summary", None):
        parts.extend([
            '<div class="section">',
            "    <h2>Profile Summary</h2>",
            f"    <p>{escape(model.summary)}</p>",
            "</div>",
        ])

    education = getattr(model, "education", [])

    if education:
        parts.extend([
            '<div class="section">',
            "    <h2>Education</h2>",
            "    <ul>",
        ])

        for record in education:
            parts.append(f"        <li>{escape(record)}</li>")

        parts.extend([
            "    </ul>",
            "</div>",
        ])

    experiences = getattr(model, "experiences", [])

    if experiences:
        parts.extend([
            '<div class="section">',
            "    <h2>Experience</h2>",
        ])

        for experience in experiences:
            if getattr(experience, "role", None):
                parts.append(
                    f"    <h3>{escape(experience.role)}</h3>"
                )

            organization = getattr(experience, "organization", None)

            if organization:
                metadata = (
                    f"{escape(organization)} · {experience.years} years"
                )
            else:
                metadata = f"{experience.years} years"

            parts.append(
                f'    <p class="metadata">{metadata}</p>'
            )
            parts.append(
                f"    <p>{escape(experience.description)}</p>"
            )

            highlights = getattr(experience, "highlights", [])

            if highlights:
                parts.append("    <ul>")

                for highlight in highlights:
                    parts.append(
                        f"        <li>{escape(highlight)}</li>"
                    )

                parts.append("    </ul>")

        parts.append("</div>")

    parts.extend([
        '<div class="section">',
        "    <h2>Normalized Technical Skills</h2>",
        '    <div class="skills">',
    ])

    for skill in model.skills:
        parts.append(
            f'        <span class="skill">{escape(skill)}</span>'
        )

    parts.extend([
        "    </div>",
        "</div>",
        '<div class="section">',
        "    <h2>Qualification Evaluation</h2>",
    ])

    classifications = getattr(model, "classifications", [])

    if classifications:
        for classification in classifications:
            profile = get_profile(classification.profile)

            parts.extend([
                '    <div class="evaluation">',
                _paragraph("Profile evaluated", profile.display_name),
                (
                    "        <p><strong>Qualification pattern:</strong> "
                    '<span class="accepted">ACCEPTED</span></p>'
                ),
                (
                    "        <p>"
                    + escape(", ".join(classification.qualifications))
                    + "</p>"
                ),
                "    </div>",
            ])
    else:
        parts.append("    <p>No matching profile</p>")

    parts.extend([
        "</div>",
        "</div>",
        "</body>",
        "</html>",
    ])

    return "\n".join(parts)


def save_html(html: str, path: str) -> None:
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(html, encoding="utf-8")